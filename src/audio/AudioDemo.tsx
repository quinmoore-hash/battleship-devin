import { useEffect, useSyncExternalStore } from 'react'
import './audio.css'
import { AudioSettings } from './AudioSettings'
import { initAudio, playSfx, startAmbience, startMusic, stopAmbience, stopMusic, useAudioRuntime } from './index'
import { LOOP_FILES, SFX_FILES, SFX_NAMES, type Sfx } from './manifest'
import { AUDIO_SETTINGS_STORAGE_KEY, useAudioSettings } from './settings'

const SFX_BLURB: Record<Sfx, string> = {
  fire: 'Pebble launch: whoosh + thump',
  hit: 'Explosion with crackle',
  miss: 'Water splash + droplets',
  sunk: 'Deep rumble, bubbles, sad otter squeak',
  victory: 'Fanfare with otter chirps',
  defeat: 'Descending womp',
  'ui-click': 'Soft pop',
  place: 'Wooden clunk',
}

const readStored = () => localStorage.getItem(AUDIO_SETTINGS_STORAGE_KEY) ?? '(nothing stored yet)'
// zustand/persist writes to storage right after notifying subscribers, so re-read on the next microtask too.
const subscribeStored = (cb: () => void) => useAudioSettings.subscribe(() => queueMicrotask(cb))

function useStoredValue(): string {
  return useSyncExternalStore(subscribeStored, readStored, () => '')
}

/** Review page: every SFX with a play button, music + ambience toggles, the settings component, and the persisted JSON. */
export function AudioDemo() {
  const { unlocked, musicPlaying: music, ambiencePlaying: ambience } = useAudioRuntime()
  const stored = useStoredValue()

  useEffect(() => initAudio(), [])

  const toggleMusic = () => {
    if (music) stopMusic()
    else startMusic()
  }
  const toggleAmbience = () => {
    if (ambience) stopAmbience()
    else startAmbience()
  }

  return (
    <main className="audio-demo" data-testid="audio-demo">
      <header>
        <img src={`${import.meta.env.BASE_URL}assets/devin-otter.png`} alt="Devin the Otter" />
        <div>
          <h1>Audio review: Devin the Otter</h1>
          <p style={{ margin: 0, opacity: 0.8 }}>
            Every sound is generated by <code>scripts/generate-audio.mjs</code>. Variants and ±5% pitch jitter keep repeats fresh.
          </p>
        </div>
      </header>

      {!unlocked && (
        <div className="audio-demo__banner" data-testid="audio-demo-locked">
          Audio is locked by the browser until you interact: click anywhere to unlock.
        </div>
      )}

      <section className="audio-demo__section">
        <h2>Sound effects</h2>
        <ul className="audio-demo__sfx">
          {SFX_NAMES.map((name) => (
            <li key={name}>
              <div>
                <strong>{name}</strong>
                <br />
                <small>
                  {SFX_BLURB[name]} · {SFX_FILES[name].length} variant{SFX_FILES[name].length > 1 ? 's' : ''}
                </small>
              </div>
              <button type="button" data-testid={`audio-play-${name}`} onClick={() => playSfx(name)}>
                Play
              </button>
            </li>
          ))}
        </ul>
      </section>

      <section className="audio-demo__section">
        <h2>Loops</h2>
        <div className="audio-demo__loops">
          <button type="button" data-testid="audio-music-toggle" aria-pressed={music} onClick={toggleMusic}>
            {music ? 'Stop music' : 'Start music'} <small>({LOOP_FILES.music}, 64 s loop)</small>
          </button>
          <button type="button" data-testid="audio-ambience-toggle" aria-pressed={ambience} onClick={toggleAmbience}>
            {ambience ? 'Stop ambience' : 'Start ambience'} <small>({LOOP_FILES.ambience}, 40 s loop)</small>
          </button>
        </div>
        <p style={{ opacity: 0.8, marginBottom: 0 }}>
          With music running, play <strong>sunk</strong>, <strong>victory</strong> or <strong>defeat</strong> to hear the ducking.
        </p>
      </section>

      <section className="audio-demo__section">
        <h2>Settings (persisted)</h2>
        <AudioSettings />
        <p style={{ opacity: 0.8 }}>
          localStorage[<code>{AUDIO_SETTINGS_STORAGE_KEY}</code>] — reload the page and the sliders keep their values:
        </p>
        <pre data-testid="audio-stored-json">{stored}</pre>
      </section>
    </main>
  )
}

export default AudioDemo
